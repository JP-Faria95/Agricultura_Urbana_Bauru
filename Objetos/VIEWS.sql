/* 1 - ATIVIDADES DESENVOLVIDAS POR AGRICULTORES */

SELECT A.ID_AGRICULTOR, A.AGRICULTOR,
       C.ATIVIDADE, C.DESCRICAO AS DESCRICAO_ATIVIDADE,
       D.CATEGORIA
FROM AGRICULTORES A
INNER JOIN AGRICULTORES_ATIVIDADES B ON A.ID_AGRICULTOR = B.ID_AGRICULTOR
INNER JOIN ATIVIDADES C ON B.ID_ATIVIDADE = C.ID_ATIVIDADE
INNER JOIN ATIVIDADES_CATEGORIAS D ON C.ID_CATEGORIA = D.ID_CATEGORIA
ORDER BY A.ID_AGRICULTOR

/* 2 - AGRICULTORES COM VIVENCIA RURAL E SUAS ATIVIDADES */

SELECT A.ID_AGRICULTOR AS ID, A.AGRICULTOR,
       B.DESCRICAO AS VIVENCIA_RURAL, B.FUNCIONAMENTO, B.ESTACIONAMENTO, B.ACESSIBILIDADE_PCD,
       LISTAGG(D.ATIVIDADE, '; ') WITHIN GROUP (ORDER BY D.ATIVIDADE) AS ATIVIDADES
FROM AGRICULTORES A
INNER JOIN VIVENCIA_RURAL B ON A.ID_AGRICULTOR = B.ID_AGRICULTOR
INNER JOIN VIVENCIA_RURAL_ATIVIDADES C ON B.ID_VIVENCIA_RURAL = C.ID_VIVENCIA
INNER JOIN ATIVIDADES D ON C.ID_ATIVIDADE = D.ID_ATIVIDADE
GROUP BY A.ID_AGRICULTOR, A.AGRICULTOR, B.DESCRICAO, B.FUNCIONAMENTO, B.ESTACIONAMENTO, B.ACESSIBILIDADE_PCD
ORDER BY A.ID_AGRICULTOR;

/* 3 - ATRATIVOS TURISTICOS ASSOCIADOS A ALGUMA ORGANIZAÇÃO */

SELECT A.ID_ATRATIVO AS ID, A.ATRATIVO, A.DESCRICAO, C.ORGANIZACAO_SIGLA, C.ORGANIZACAO_NOME, C.EMAIL AS ORGANIZACAO_CONTATO
FROM ATRATIVOS_TURISTICOS A
INNER JOIN ATRATIVOS_TURISTICOS_ORGANIZACOES B ON A.ID_ATRATIVO = B.ID_ATRATIVO
INNER JOIN ORGANIZACOES C ON B.ID_ORGANIZACAO = C.ID_ORGANIZACAO
ORDER BY A.ID_ATRATIVO;

/* 4 - PERFIL (ATIVIDADES E SUBCATEGORIAS) DAS FEIRAS QUE OCORREM NO MUNICIPIO DE BAURU */

WITH

FEIRAS_ATIVIDADES AS
(SELECT A.ID_FEIRA, LISTAGG(B.ATIVIDADE, '; ') WITHIN GROUP (ORDER BY B.ATIVIDADE) AS ATIVIDADES
 FROM FEIRAS_MUNICIPAIS_ATIVIDADES A
 INNER JOIN ATIVIDADES B ON A.ID_ATIVIDADE = B.ID_ATIVIDADE
 GROUP BY A.ID_FEIRA),

FEIRAS_SUBCATEGORIAS AS
(SELECT A.ID_FEIRA, LISTAGG(B.SUBCATEGORIA, '; ') WITHIN GROUP (ORDER BY B.SUBCATEGORIA) AS SUBCATEGORIAS
 FROM FEIRAS_MUNICIPAIS_SUBCATEGORIAS A
 INNER JOIN SUBCATEGORIAS B ON A.ID_SUBCATEGORIA = B.ID_SUBCATEGORIA
 GROUP BY A.ID_FEIRA)

SELECT A.ID_FEIRA, A.FEIRA, A.EMAIL AS CONTATO, A.FUNCIONAMENTO, B.ATIVIDADES, C.SUBCATEGORIAS
FROM FEIRAS_MUNICIPAIS A
INNER JOIN FEIRAS_ATIVIDADES B ON A.ID_FEIRA = B.ID_FEIRA
INNER JOIN FEIRAS_SUBCATEGORIAS C ON A.ID_FEIRA = C.ID_FEIRA
INNER JOIN LOCALIZACOES D ON A.ID_LOCAL = D.ID_LOCAL
WHERE D.MUNICIPIO = 'BAURU'

/* 5 - HORTAS COM CERTIFICAÇÕES */

SELECT A.ID_HORTA, A.HORTA, 
       CASE WHEN C.CERTIFICACAO_SIGLA IS NULL THEN 'NÃO POSSUI CERTIFICAÇÃO' ELSE CERTIFICACAO_SIGLA END AS CERTIFICACAO_SIGLA,
       CASE WHEN C.CERTIFICACAO_NOME IS NULL THEN 'NÃO POSSUI CERTIFICAÇÃO' ELSE CERTIFICACAO_NOME END AS CERTIFICACAO_NOME,
       CASE WHEN B.DT_CERTIFICADO IS NULL THEN 'NÃO POSSUI CERTIFICAÇÃO' ELSE TO_CHAR(B.DT_CERTIFICADO) END AS DT_CERTIFICADO,
       B.CERTIFICADO
FROM HORTAS_URBANAS A
LEFT JOIN HORTAS_URBANAS_CERTIFICACOES B ON A.ID_HORTA = B.ID_HORTA
LEFT JOIN CERTIFICACOES C ON B.ID_CERTIFICACAO = C.ID_CERTIFICACAO
ORDER BY A.ID_HORTA, B.ID_CERTIFICACAO

/* 6 - HORTAS URBANAS E PONTOS DE VENDAS */

SELECT A.ID_HORTA AS ID, A.HORTA, C.PONTO_VENDA, D.CEP AS CEP_PONTO_VENDA, D.MUNICIPIO AS MUNICIPIO_PONTO_VENDA
FROM HORTAS_URBANAS A
INNER JOIN HORTAS_URBANAS_PONTOS_VENDA B ON A.ID_HORTA = B.ID_HORTA
INNER JOIN PONTOS_VENDA C ON B.ID_PONTO_VENDA = C.ID_PONTO
INNER JOIN LOCALIZACOES D ON C.ID_LOCAL = D.ID_LOCAL
ORDER BY A.ID_HORTA

/* 7 - LOCALIZAÇÃO COMPLETA DE CADA HORTA */

SELECT A.ID_HORTA, A.HORTA, B.ENDERECO, B.BAIRRO, B.CEP, B.LATITUDE, B.LONGITUDE, C.ZONA, B.MUNICIPIO, B.UF
FROM HORTAS_URBANAS A
INNER JOIN LOCALIZACOES B ON A.ID_LOCAL = B.ID_LOCAL
INNER JOIN ZONAS C ON B.ID_ZONA = C.ID_ZONA
ORDER BY A.ID_HORTA;

/* 8 - SUBCATEGORIAS A QUAL UMA INICIATIVA PÚBLICA PERTENCE SE ESTIVER ATIVA */

SELECT A.ID_INICIATIVA AS ID, A.INICIATIVA, A.DESCRICAO, A.ATUACAO, B.TIPO, LISTAGG(D.SUBCATEGORIA, '; ') WITHIN GROUP (ORDER BY D.SUBCATEGORIA) AS SUBCATEGORIAS
FROM INICIATIVAS_PUBLICAS A
INNER JOIN INICIATIVAS_PUBLICAS_TIPOS B ON A.ID_TIPO_INICIATIVA = B.ID_TIPO
INNER JOIN INICIATIVAS_PUBLICAS_SUBCATEGORIAS C ON A.ID_INICIATIVA = C.ID_INICIATIVA
INNER JOIN SUBCATEGORIAS D ON C.ID_SUBCATEGORIA = D.ID_SUBCATEGORIA
WHERE A.ATIVO = 'S'
GROUP BY A.ID_INICIATIVA, A.INICIATIVA, A.DESCRICAO, A.ATUACAO, B.TIPO
ORDER BY A.ID_INICIATIVA;

/* 9 - CLASSIFICAÇÃO DOS SERVIÇOS PARA AGRICULTURA EM SUBCATEGORIAS E QUAIS ATIVIDADES PROMOVEM NA CIDADE DE BAURU */

WITH

SUBCATEGORIAS_SERVICOS AS
(SELECT A.ID_SERVICO, A.SERVICO, LISTAGG(C.SUBCATEGORIA, '; ') WITHIN GROUP (ORDER BY C.SUBCATEGORIA) AS SUBCATEGORIAS
 FROM SERVICOS_AGRICULTURA A
 INNER JOIN SERVICOS_AGRICULTURA_SUBCATEGORIAS B ON A.ID_SERVICO = B.ID_SERVICO
 INNER JOIN SUBCATEGORIAS C ON B.ID_SUBCATEGORIA = C.ID_SUBCATEGORIA
 GROUP BY A.ID_SERVICO, A.SERVICO),

ATIVIDADES_SERVICOS AS
(SELECT A.ID_SERVICO, A.SERVICO, LISTAGG(C.ATIVIDADE, '; ') WITHIN GROUP (ORDER BY C.ATIVIDADE) AS ATIVIDADES
FROM SERVICOS_AGRICULTURA A
INNER JOIN SERVICOS_AGRICULTURA_ATIVIDADES B ON A.ID_SERVICO = B.ID_SERVICO
INNER JOIN ATIVIDADES C ON B.ID_ATIVIDADE = C.ID_ATIVIDADE
GROUP BY A.ID_SERVICO, A.SERVICO)

SELECT A.ID_SERVICO, A.SERVICO, B.SUBCATEGORIAS, C.ATIVIDADES
FROM SERVICOS_AGRICULTURA A
INNER JOIN SUBCATEGORIAS_SERVICOS B ON A.ID_SERVICO = B.ID_SERVICO
INNER JOIN ATIVIDADES_SERVICOS C ON A.ID_SERVICO = C.ID_SERVICO
INNER JOIN LOCALIZACOES D ON A.ID_LOCAL = D.ID_LOCAL
WHERE D.MUNICIPIO = 'BAURU'

/* 10 - EXIBIR O PERFIL DAS VIVÊNCIAS RURAIS, MOSTRANDO QUAL ENTIDADE É 'DONA' DESTA VIVENCIA, A LOCALIZAÇÃO, QUAIS ATIVIDADES SÃO DESENVOLVIDAS NA ÁREA E
SE POSSUI ALGUMA QUALIFICAÇÃO */

WITH

VIVENCIA_RURAL_HORTAS_ATIVIDADES AS
(SELECT A.ID_HORTA, A.HORTA, LISTAGG(C.ATIVIDADE, '; ') WITHIN GROUP (ORDER BY C.ATIVIDADE) AS ATIVIDADES,
        D.ENDERECO, D.CEP, D.MUNICIPIO
FROM HORTAS_URBANAS A
INNER JOIN HORTAS_URBANAS_ATIVIDADES B ON A.ID_HORTA = B.ID_HORTA
INNER JOIN ATIVIDADES C ON B.ID_ATIVIDADE = C.ID_ATIVIDADE
INNER JOIN LOCALIZACOES D ON A.ID_LOCAL = D.ID_LOCAL
GROUP BY A.ID_HORTA, A.HORTA,D.ENDERECO, D.CEP, D.MUNICIPIO),

VIVENCIA_RURAL_AGRICULTORES_ATIVIDADES AS
(SELECT A.ID_AGRICULTOR, A.AGRICULTOR, LISTAGG(C.ATIVIDADE, '; ') WITHIN GROUP (ORDER BY C.ATIVIDADE) AS ATIVIDADES,
        D.ENDERECO, D.CEP, D.MUNICIPIO
FROM AGRICULTORES A
INNER JOIN AGRICULTORES_ATIVIDADES B ON A.ID_AGRICULTOR = B.ID_AGRICULTOR
INNER JOIN ATIVIDADES C ON B.ID_ATIVIDADE = C.ID_ATIVIDADE
INNER JOIN LOCALIZACOES D ON A.ID_LOCAL = D.ID_LOCAL
GROUP BY A.ID_AGRICULTOR, A.AGRICULTOR, D.ENDERECO, D.CEP, D.MUNICIPIO)

SELECT A.ID_VIVENCIA_RURAL AS ID,
       CASE WHEN
            A.ID_AGRICULTOR IS NOT NULL THEN 'AGRICULTOR'
            ELSE 'HORTA URBANA'
       END AS ENTIDADE_TIPO,
       COALESCE(B.HORTA, C.AGRICULTOR) AS ENTIDADE_NOME,
       A.ACESSIBILIDADE_PCD, A.ESTACIONAMENTO, A.DESCRICAO, A.FUNCIONAMENTO,
       COALESCE(B.ENDERECO, C.ENDERECO) AS ENDERECO,
       COALESCE(B.CEP, C.CEP) AS CEP,
       COALESCE(B.MUNICIPIO, C.MUNICIPIO) AS MUNICIPIO,
       CASE WHEN
            A.ID_AGRICULTOR IS NOT NULL THEN (SELECT D.ATIVIDADES FROM VIVENCIA_RURAL_AGRICULTORES_ATIVIDADES D WHERE D.ID_AGRICULTOR = A.ID_AGRICULTOR)
            ELSE (SELECT B.ATIVIDADES FROM VIVENCIA_RURAL_HORTAS_ATIVIDADES B WHERE B.ID_HORTA = A.ID_HORTA)
       END AS ATIVIDADES,
      COALESCE((SELECT LISTAGG(E.QUALIFICACAO, '; ') WITHIN GROUP (ORDER BY E.QUALIFICACAO) AS QUALIFICACOES
                FROM VIVENCIA_RURAL_QUALIFICACOES E
                WHERE E.ID_VIVENCIA = A.ID_VIVENCIA_RURAL
                GROUP BY E.ID_VIVENCIA), 'Não possui qualificações') AS QUALIFICACOES
FROM VIVENCIA_RURAL A
LEFT JOIN VIVENCIA_RURAL_HORTAS_ATIVIDADES B ON A.ID_HORTA = B.ID_HORTA
LEFT JOIN VIVENCIA_RURAL_AGRICULTORES_ATIVIDADES C ON A.ID_AGRICULTOR = C.ID_AGRICULTOR
ORDER BY A.ID_VIVENCIA_RURAL;