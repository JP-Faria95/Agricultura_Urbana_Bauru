/* FUNCTION FC_CONVERTER_BASE64_TO_BLOB
-> FUNÇÃO RESPONSÁVEL POR CONVERTER UM ARQUIVO BASE64 EM BLOB
-> UTIL PARA CERTIFICADOS COMO NAS TABELAS DE CERTIFICACOES E QUALIFICAÇÕES
-> RECEBE COMO PARAMETRO APENAS O ARQUIVO BASE64 E DEVOLVE O MESMO ARQUIVO EM BLOB
*/

CREATE OR REPLACE FUNCTION FC_CONVERTER_BASE64_TO_BLOB
(FC_ARQUIVO_BASE64 IN CLOB)
RETURN BLOB
AS
    V_BLOB       BLOB;
    V_TEXTO      VARCHAR2(16000);
    V_RAW        RAW(32767);
    V_POSICAO    NUMBER := 1;
    V_TAMANHO    NUMBER;
    V_BLOCO      CONSTANT PLS_INTEGER := 16000;

BEGIN
    V_TAMANHO := DBMS_LOB.GETLENGTH(FC_ARQUIVO_BASE64);
    IF V_TAMANHO = 0 THEN
        RETURN NULL;
    END IF;
    DBMS_LOB.CREATETEMPORARY(V_BLOB, TRUE);

    WHILE V_POSICAO <= V_TAMANHO LOOP

        -- EXTRAI UM TRECHO DO CLOB
        V_TEXTO := DBMS_LOB.SUBSTR(FC_ARQUIVO_BASE64, V_BLOCO,V_POSICAO);

        -- VALIDA OS CARACTERES BASE64
        IF V_POSICAO + LENGTH(V_TEXTO) - 1 < V_TAMANHO THEN
            IF NOT REGEXP_LIKE(V_TEXTO, '^[A-Za-z0-9+/]+$') THEN
                RAISE_APPLICATION_ERROR(-20031, 'CONTEÚDO BASE64 INVÁLIDO');
            END IF;
        ELSE
            IF NOT REGEXP_LIKE(V_TEXTO, '^[A-Za-z0-9+/]+={0,2}$') THEN
                RAISE_APPLICATION_ERROR(-20031, 'CONTEÚDO BASE64 INVÁLIDO');
            END IF;
        END IF;

        -- CONVERTE O TEXTO BASE64 PARA BINARIO
        V_RAW := UTL_ENCODE.BASE64_DECODE(UTL_RAW.CAST_TO_RAW(V_TEXTO));

        -- ADICIONA O BLOCO DECODIFICADO AO BLOB
        DBMS_LOB.WRITEAPPEND(V_BLOB, UTL_RAW.LENGTH(V_RAW), V_RAW);

        -- AVANCA PARA O PROXIMO BLOCO
        V_POSICAO := V_POSICAO + V_BLOCO;

    END LOOP;

    RETURN V_BLOB;

    EXCEPTION
        WHEN OTHERS THEN
            IF V_BLOB IS NOT NULL THEN
                IF DBMS_LOB.ISTEMPORARY(V_BLOB) = 1 THEN
                    DBMS_LOB.FREETEMPORARY(V_BLOB);
                END IF;
            END IF;
            RAISE;

END FC_CONVERTER_BASE64_TO_BLOB;