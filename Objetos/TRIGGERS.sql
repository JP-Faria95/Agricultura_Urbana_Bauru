CREATE OR REPLACE TRIGGER TRG_LOG_AGRICULTORES
AFTER INSERT OR UPDATE OR DELETE ON AGRICULTORES
FOR EACH ROW

BEGIN

    IF INSERTING THEN

        INSERT INTO LOG_OPERACOES (TABELA, OPERACAO, ID_REGISTRO, USUARIO, DATA_HORA)
        VALUES ('AGRICULTORES', 'INSERT', :NEW.ID_AGRICULTOR, SYS_CONTEXT('USERENV', 'SESSION_USER'), SYSDATE);

    ELSIF UPDATING THEN

        INSERT INTO LOG_OPERACOES (TABELA, OPERACAO, ID_REGISTRO, USUARIO, DATA_HORA)
        VALUES ('AGRICULTORES', 'UPDATE', :NEW.ID_AGRICULTOR, SYS_CONTEXT('USERENV', 'SESSION_USER'), SYSDATE);

    ELSIF DELETING THEN

        INSERT INTO LOG_OPERACOES (TABELA, OPERACAO, ID_REGISTRO, USUARIO, DATA_HORA)
        VALUES ('AGRICULTORES', 'DELETE', :OLD.ID_AGRICULTOR, SYS_CONTEXT('USERENV', 'SESSION_USER'), SYSDATE);

    END IF;

END;
