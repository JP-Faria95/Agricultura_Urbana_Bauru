CREATE TABLE PARCEIROS
(ID_PARCEIRO NUMBER DEFAULT SEQ_IDPARCEIRO_PARCEIROS.NEXTVAL NOT NULL,
PARCEIRO VARCHAR2(240) NOT NULL,
EMAIL VARCHAR(120),
TELEFONE_1 VARCHAR2(20),
TELEFONE_2 VARCHAR2(20),
DESCRICAO VARCHAR2(4000),
FUNCIONAMENTO VARCHAR2(480),
ID_LOCAL NUMBER,
CONSTRAINT FK_IDLOCAL_PARCEIROS FOREIGN KEY (ID_LOCAL) REFERENCES LOCALIZACOES (ID_LOCAL));

ALTER TABLE PARCEIROS ADD CONSTRAINT PK_IDPARCEIRO_PARCEIROS PRIMARY KEY (ID_PARCEIRO);

CREATE SEQUENCE SEQ_IDPARCEIRO_PARCEIROS
START WITH 1
INCREMENT BY 1
MINVALUE 1
MAXVALUE 99999
NOCACHE NOCYCLE; 

